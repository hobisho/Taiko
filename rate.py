# ========== 指標計算區 ==========

def to_binary(chart):
    """ 將0/1/2轉成是否有敲擊 (0:沒敲, 1或2:有敲) """
    return [int(x > 0) for x in chart]

def direct_comparison(x, y):
    """ 一對一比對（相等比例） """
    return np.mean(np.array(x) == np.array(y))

def onset_comparison(human, ai, tolerance=1):
    """
    有寬容的onset比對。
    只考慮human有敲擊(1)的位置，ai在[tolerance]範圍內有1即算正確。
    """
    human_bin = to_binary(human)
    ai_bin = to_binary(ai)
    hit_count = 0
    total_count = 0
    L = len(human_bin)
    for i in range(L):
        if human_bin[i] == 1:
            total_count += 1
            match = False
            # 在 [i-tolerance, i+tolerance] 範圍內尋找 ai 是否有標1
            for j in range(max(0, i-tolerance), min(L, i+tolerance+1)):
                if ai_bin[j] == 1:
                    match = True
                    break
            if match:
                hit_count += 1
    return hit_count / total_count if total_count > 0 else 0

